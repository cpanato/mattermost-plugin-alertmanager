func TestSeverityColors(t *testing.T) {
	for _, tc := range []struct{ severity, color string }{
		{"info", "#3498DB"}, {"warning", "#FFCC00"}, {"high", "#FF0000"},
		{"critical", "#FF0000"}, {" WaRnInG ", "#FFCC00"}, {"", "#FF0000"}, {"custom", "#FF0000"},
	} {
		t.Run(tc.severity, func(t *testing.T) {
			require.Equal(t, tc.color, setColor("firing", tc.severity))
			require.Equal(t, "#008000", setColor("resolved", tc.severity))
			require.Equal(t, "#F0F8FF", setColor("unknown", tc.severity))
		})
	}
}

func TestWebhookSeverityColors(t *testing.T) {
	api := &plugintest.API{}
	api.On("LogInfo", mock.Anything).Return()
	api.On("CreatePost", mock.Anything).Run(func(args mock.Arguments) {
		post := args.Get(0).(*model.Post)
		require.Equal(t, "channel", post.ChannelId)
		attachments := post.Attachments()
		require.Len(t, attachments, 5)
		for i, color := range []string{"#3498DB", "#FFCC00", "#FF0000", "#008000", "#FF0000"} {
			require.Equal(t, color, attachments[i].Color)
		}
	}).Return(&model.Post{}, (*model.AppError)(nil)).Once()
	p := &Plugin{BotUserID: "bot", AlertConfigIDChannelID: map[string]string{"0": "channel"}}
	p.SetAPI(api)
	body, err := json.Marshal(template.Data{Status: "firing", Alerts: template.Alerts{
		{Status: "firing", Labels: template.KV{"severity": "info"}},
		{Status: "firing", Labels: template.KV{"severity": "warning"}},
		{Status: "firing", Labels: template.KV{"severity": "critical"}},
		{Status: "resolved", Labels: template.KV{"severity": "critical"}},
		{Status: "firing"},
	}})
	require.NoError(t, err)
	w := httptest.NewRecorder()
	p.handleWebhook(w, httptest.NewRequest(http.MethodPost, "/", bytes.NewReader(body)), alertConfig{ID: "0"})
	require.Equal(t, http.StatusOK, w.Code)
	api.AssertExpectations(t)
}

func TestWebhookAlertPresentation(t *testing.T) {
	startsAt := time.Now().Add(-time.Hour)
	endsAt := time.Now().Add(-time.Minute)
	alert := template.Alert{
		Status: "resolved", StartsAt: startsAt, EndsAt: endsAt,
		GeneratorURL: "https://prometheus.example.com/graph",
		Labels: template.KV{
			"alertname": "CheckoutLatencyHigh", "severity": "warning", "instance": "checkout-1",
		},
		Annotations: template.KV{
			"summary":     "Checkout latency above 2 seconds",
			"description": "p95 latency exceeded the threshold.",
			"runbook_url": "https://runbooks.example.com/checkout",
			"dashboard":   "https://grafana.example.com/checkout",
		},
	}
	attachment := convertAlertToAttachment(alertConfig{ID: "east"}, alert, "https://alertmanager.example.com", "platform")
	require.Equal(t, "RESOLVED: CheckoutLatencyHigh", attachment.Title)
	require.True(t, strings.HasPrefix(attachment.Text, "**Checkout latency above 2 seconds**\n\np95 latency exceeded the threshold."))
	require.Contains(t, attachment.Text, "**Dashboard:** https://grafana.example.com/checkout")
	require.Contains(t, attachment.Text, "**Runbook_url:** https://runbooks.example.com/checkout")
	require.Equal(t, "Config: east · Receiver: platform", attachment.Footer)
	require.Len(t, attachment.Fields, 3)
	require.Contains(t, attachment.Fields[0].Value, "**Started:** "+startsAt.UTC().Format(time.RFC3339))
	require.Contains(t, attachment.Fields[0].Value, "**Ended:** "+endsAt.UTC().Format(time.RFC3339))
	require.Contains(t, attachment.Fields[1].Value, "**Instance:** checkout-1")
	require.Equal(t, "[Prometheus](https://prometheus.example.com/graph) · [Alertmanager](https://alertmanager.example.com)", attachment.Fields[2].Value)
	data, err := json.Marshal(attachment)
	require.NoError(t, err)
	require.NotContains(t, string(data), "Generated by")
	require.Equal(t, template.KV{"alertname": "CheckoutLatencyHigh", "severity": "warning", "instance": "checkout-1"}, alert.Labels)
	empty := convertAlertToAttachment(alertConfig{}, template.Alert{Status: "firing"}, "", "")
	require.Equal(t, "FIRING", empty.Title)
	require.Empty(t, empty.Text)
	require.Empty(t, empty.Fields)
}

func TestAlertCommandSeverityColors(t *testing.T) {
	now := time.Now()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		require.Equal(t, "/api/v2/alerts", r.URL.Path)
		require.NoError(t, json.NewEncoder(w).Encode([]map[string]any{
			{"labels": map[string]string{"alertname": "info", "severity": "info"}, "startsAt": now.Add(-time.Minute), "endsAt": now.Add(time.Hour)},
			{"labels": map[string]string{"alertname": "warning", "severity": "warning"}, "startsAt": now.Add(-time.Minute), "endsAt": now.Add(time.Hour)},
			{"labels": map[string]string{"alertname": "critical", "severity": "critical"}, "startsAt": now.Add(-time.Minute), "endsAt": now.Add(time.Hour)},
			{"labels": map[string]string{"alertname": "resolved", "severity": "critical"}, "startsAt": now.Add(-time.Hour), "endsAt": now.Add(-time.Minute)},
			{"labels": map[string]string{"alertname": "missing"}, "startsAt": now.Add(-time.Minute), "endsAt": now.Add(time.Hour)},
		}))
	}))
	defer server.Close()
	api := &plugintest.API{}
	api.On("CreatePost", mock.Anything).Run(func(args mock.Arguments) {
		post := args.Get(0).(*model.Post)
		require.Equal(t, "channel", post.ChannelId)
		require.Equal(t, "thread", post.RootId)
		attachments := post.Attachments()
		require.Len(t, attachments, 5)
		for i, color := range []string{"#3498DB", "#FFCC00", "#FF0000", "#008000", "#FF0000"} {
			require.Equal(t, color, attachments[i].Color, attachments[i].Title)
		}
	}).Return(&model.Post{}, (*model.AppError)(nil)).Once()
	p := &Plugin{BotUserID: "bot", AlertConfigIDChannelID: map[string]string{"0": "channel"}}
	p.SetAPI(api)
	p.setConfiguration(&configuration{AlertConfigs: map[string]alertConfig{"0": {ID: "0", AlertManagerURL: server.URL}}})
	message, err := p.handleAlert(&model.CommandArgs{RootId: "thread"})
	require.NoError(t, err)
	require.Empty(t, message)
	api.AssertExpectations(t)
}
